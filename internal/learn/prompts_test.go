// TestPastesBounded: the fallback is linear in the prompt (and not tried
// past maxFitText), and pairing is not prompts × entries.
func TestPastesBounded(t *testing.T) {
	const stored = `{"1":{"id":1,"type":"text","contentHash":"a"},"2":{"id":2,"type":"text","contentHash":"b"}}`
	for _, n := range []int{900 << 10, 2 << 20} {
		text := "x" + strings.Repeat("a", n) + "END"
		start := time.Now()
		got := pastesRun(t, []string{hist("x[Pasted text #1 +5 lines]a[Pasted text #2 +5 lines]END", 0, stored)}, []int{0}, []string{text})
		if el := time.Since(start); el > time.Second {
			t.Errorf("%d bytes: %v", n, el)
		}
		if len(got) != 1 || strings.Contains(got[0], pastedMark) || !strings.HasPrefix(got[0], "xaaa") {
			t.Errorf("%d bytes: changed", n)
		}
	}

	var history []string
	for i := range maxPastes {
		history = append(history, fmt.Sprintf(`{"display":"typed %d","pastedContents":{},"timestamp":%d,"project":"/p","sessionId":"s1"}`, i, t0.UnixMilli()+int64(i)))
	}
	var at []int
	var texts []string
	for i := range 20000 {
		at = append(at, 3600+i)
		texts = append(texts, fmt.Sprintf("unmatched %d", i))
	}
	texts[19999] = "typed 49999"
	start := time.Now()
	got := pastesRun(t, history, at, texts)
	if el := time.Since(start); el > 3*time.Second {
		t.Errorf("50000 entries, 20000 prompts: %v", el)
	}
	if len(got) != 20000 || got[19999] != "typed 49999" {
		t.Errorf("%d prompts", len(got))
	}
}

