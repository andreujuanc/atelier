// human is a typed prompt as recent Claude Code writes it.
func human(content string) string {
	return `{"type":"user","origin":{"kind":"human"},"promptSource":"typed","timestamp":"2026-05-01T10:00:00Z","message":{"role":"user","content":` + content + `}}`
}

// legacy is a user entry as older Claude Code writes it: no origin.
func legacy(content string) string {
	return `{"type":"user","userType":"external","timestamp":"2026-05-01T10:00:00Z","message":{"role":"user","content":` + content + `}}`
}

func assistant(blocks string) string {
	return `{"type":"assistant","timestamp":"2026-05-01T10:00:01Z","message":{"role":"assistant","content":` + blocks + `}}`
}

func prompts(t *testing.T, cfg Config, lines ...string) []Prompt {
	t.Helper()
	ps, err := ParsePrompts(strings.NewReader(strings.Join(lines, "\n")+"\n"), cfg)
	if err != nil {
		t.Fatal(err)
	}
	return ps
}

