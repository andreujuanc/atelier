// Package gen generates the per-task files atelier writes into a task
// directory: CLAUDE.md and .claude/settings.json.
package gen

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/andreujuanc/atelier/internal/model"
)

// RepoInfo describes one repo of a task as seen from the task directory.
type RepoInfo struct {
	Name string
	Mode model.Mode
	Path string // absolute: the git worktree (rw) or the canonical repo (ro)
}

// WriteClaudeMD writes <taskDir>/CLAUDE.md describing the task, its repos
// and port offset, creating taskDir if needed.
func WriteClaudeMD(taskDir string, t model.Task, repos []RepoInfo) error {
	if err := os.MkdirAll(taskDir, 0o755); err != nil {
		return fmt.Errorf("gen: create task dir: %w", err)
	}
	path := filepath.Join(taskDir, "CLAUDE.md")
	if err := writeAtomic(path, []byte(ClaudeMD(t, repos))); err != nil {
		return fmt.Errorf("gen: write %s: %w", path, err)
	}
	return nil
}

// ClaudeMD renders the CLAUDE.md contents for a task.
func ClaudeMD(t model.Task, repos []RepoInfo) string {
	branch := t.Branch
	if branch == "" {
		branch = "atl/" + t.Slug
	}
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }

	w("<!-- generated by atelier; regenerate with atelier rather than editing by hand -->\n\n")
	w("# %s\n\n", strings.Join(strings.Fields(t.Title), " "))
	if d := strings.TrimSpace(t.Description); d != "" {
		w("%s\n\n", d)
	}
	w("- Task: `%s`\n", t.Slug)
	w("- Branch: `%s` (every rw repo below is a git worktree checked out on this branch)\n\n", branch)

	w("## Repositories\n\n")
	var ro []RepoInfo
	for _, r := range repos {
		switch r.Mode {
		case model.ModeRO:
			ro = append(ro, r)
			w("- **%s** — `%s` — **ro**: canonical repo, READ-ONLY (do not modify)\n", r.Name, r.Path)
		default:
			w("- **%s** — `%s` — **rw**: git worktree on branch `%s`; make your changes here\n", r.Name, r.Path, branch)
		}
	}
	w("\n")

	if len(ro) > 0 {
		w("## READ-ONLY repositories — do NOT modify\n\n")
		w("The following repos are shared canonical clones used by other tasks:\n\n")
		for _, r := range ro {
			w("- `%s` (%s)\n", r.Path, r.Name)
		}
		w("\n")
		w("They must NOT be modified by any means:\n\n")
		w("- Not with the Edit, Write, MultiEdit or NotebookEdit tools. Edits/writes into them are blocked by an atelier hook.\n")
		w("- Not via Bash either: no shell redirects (`>`, `>>`) or `tee` into them, no `sed -i`, no `mv`/`rm`/`cp`/`touch`/`mkdir` targeting them,\n")
		w("  no `git commit`/`checkout`/`switch`/`stash`/`reset`/`pull`/`merge`/`rebase`/`clean`/`add` in them,\n")
		w("  no formatters or linters with auto-fix, no package installs (`npm install`, `go mod tidy`, `pip install`, ...),\n")
		w("  and no builds or scripts that write output (build artifacts, caches, generated files) inside them.\n\n")
		w("Read-only use is fine: reading files, `grep`/`rg`, `git log`, `git diff`, `git show`, `git blame`.\n")
		w("If a change is needed in one of them, say so instead of making it (or make it in a rw repo).\n\n")
	}

	w("## Ports\n\n")
	w("`ATL_PORT_OFFSET=%d`\n\n", t.PortOffset)
	w("`ATL_PORT_OFFSET` is also exported in the environment. Offset every port you bind so this task does not\n")
	w("collide with other tasks running in parallel: e.g. use host port `$((3000 + ATL_PORT_OFFSET))` instead of 3000.\n")
	w("docker compose files can use `${ATL_PORT_OFFSET}`.\n")
	return b.String()
}
