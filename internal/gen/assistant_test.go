func readAssistantSettings(t *testing.T, dir string) map[string]any {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(dir, ".claude", "settings.json"))
	if err != nil {
		t.Fatal(err)
	}
	var m map[string]any
	if err := json.Unmarshal(b, &m); err != nil {
		t.Fatal(err)
	}
	return m
}

func strList(t *testing.T, v any) []string {
	t.Helper()
	l, ok := v.([]any)
	if !ok {
		t.Fatalf("not a list: %#v", v)
	}
	out := make([]string, 0, len(l))
	for _, x := range l {
		s, _ := x.(string)
		out = append(out, s)
	}
	return out
}

func TestAssistantClaudeMD(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "assistant")
	if err := WriteAssistantFiles(dir, "/usr/bin/atl"); err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(filepath.Join(dir, "CLAUDE.md"))
	if err != nil {
		t.Fatal(err)
	}
	md := string(b)
	for _, want := range []string{
		"generated by atelier",
		"You are the atelier assistant",
		"Your ONLY job is managing atelier tasks",
		"You do NOT do code work",
		"Do NOT read source code in depth, review code, propose code changes, debug",
		"offer to implement anything",
		"would not be in", "the task's git worktrees",
		"belongs in the task's own Claude", "select the task and press Enter", "`atl open <task>`",
		"The task session sees the task's worktrees",
		"When greeted with \"Let's talk about task <slug>.\", immediately gather status",
		"`atl show <slug> --json` (includes the notes), `atl transcript <slug> --tail 30`",
		"goal, done, pending, blockers, suggested next step",
		"ask what the user", "resume it, add a repo, save a note, finish it",
		"ALWAYS ask for explicit confirmation",
		"state the exact command",
		"atl ls [--status", "atl show <task> [--json]", "atl transcript <task> [--session ID] [--tail N]",
		"atl show <task> --notes", "atl notes <task>", "atl note <task> <text> --author assistant", "atl notes <task> --set",
		"atl repos", "atl new ", "atl add ",
		"atl status ", "atl rename <task> <new title...>", "atl session ", "atl resume ", "atl diff ", "atl pr ", "atl done ", "atl cancel ",
		"atl show X --json", "atl show X --notes", "atl transcript X --tail 30",
		"git log", "goal, what was done, what is pending, blockers, suggested next step",
		"run `atl ls` and ask",
		"offer to append a short note",
		"Never edit files in repos",
		"Keep answers short",
		"one-step-at-a-time",
		"repo-changing commands are denied", "`git commit`", "`sed -i`", "cannot be fully",
	} {
		if !strings.Contains(md, want) {
			t.Errorf("CLAUDE.md lacks %q", want)
		}
	}
	// rename is a state-changing command: in the confirm rule and listed
	// under "Changes state", not under the read-only commands.
	if !strings.Contains(md, "`status`, `rename`, `session`") {
		t.Error("confirm rule lacks rename")
	}
	ro, changes, ok := strings.Cut(md, "Changes state (ALWAYS confirm first):")
	if !ok || strings.Contains(ro[strings.Index(ro, "Read-only (run freely):"):], "atl rename") ||
		!strings.Contains(changes, "- `atl rename <task> <new title...>` — change the task's title only") {
		t.Error("atl rename not listed (only) under the state-changing commands")
	}
	if !strings.Contains(md, "slug, branch `atl/<slug>`, tmux") {
		t.Error("rename entry does not say the slug and branch stay")
	}
	// notes: read with atl show --notes (allowed); atl note appends and
	// atl notes --set replaces, both under "Changes state", --set asks first
	readOnly := ro[strings.Index(ro, "Read-only (run freely):"):]
	if !strings.Contains(readOnly, "- `atl show <task> --notes` — only the task's notes") ||
		!strings.Contains(readOnly, "asks for permission here (its `--set` and") ||
		!strings.Contains(readOnly, "`--clear` forms write)") ||
		strings.Contains(readOnly, "--set` —") || strings.Contains(readOnly, "atl note <task>") {
		t.Error("read-only notes commands wrong")
	}
	if !strings.Contains(changes, "- `atl note <task> <text> --author assistant` — append a line `- YYYY-MM-DD [assistant] <text>`") ||
		!strings.Contains(changes, "- `atl notes <task> --set` — REPLACE the whole notes text with stdin") ||
		!strings.Contains(changes, "(an empty stdin is an error)") ||
		!strings.Contains(changes, "- `atl notes <task> --clear` — DELETE the whole notes text") ||
		!strings.Contains(changes, "get their yes first") || !strings.Contains(changes, "use `atl note` instead") {
		t.Error("notes write commands not described under the state-changing commands")
	}
	if !strings.Contains(md, "`cancel`, `note`, `notes --set`,\n  `notes --clear`)") {
		t.Error("confirm rule lacks notes --set / --clear")
	}
	// always regenerated
	if err := os.WriteFile(filepath.Join(dir, "CLAUDE.md"), []byte("tampered"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := WriteAssistantFiles(dir, "/usr/bin/atl"); err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(filepath.Join(dir, "CLAUDE.md")); string(b) != md {
		t.Fatal("CLAUDE.md not regenerated")
	}
}

func TestAssistantSettings(t *testing.T) {
	dir := t.TempDir()
	if err := WriteAssistantFiles(dir, "/opt/my atl/atl"); err != nil {
		t.Fatal(err)
	}
	m := readAssistantSettings(t, dir)
	perms := m["permissions"].(map[string]any)
	if perms["defaultMode"] != "default" {
		t.Errorf("defaultMode = %v", perms["defaultMode"])
	}
	if got := strList(t, perms["allow"]); !reflect.DeepEqual(got, assistantAllow) {
		t.Errorf("allow = %v", got)
	}
	if got := strList(t, perms["ask"]); !reflect.DeepEqual(got, assistantAsk) {
		t.Errorf("ask = %v", got)
	}
	if got := strList(t, perms["deny"]); !reflect.DeepEqual(got, assistantDeny) {
		t.Errorf("deny = %v", got)
	}
	for _, want := range []string{"Bash(git commit *)", "Bash(git push *)", "Bash(rm *)", "Bash(sed -i *)", "Bash(git branch -D *)"} {
		if !contains(strList(t, perms["deny"]), want) {
			t.Errorf("deny lacks %s", want)
		}
	}
	for _, want := range []string{"Bash(atl show *)", "Bash(atl transcript *)", "Read", "Grep", "Glob"} {
		if !contains(strList(t, perms["allow"]), want) {
			t.Errorf("allow lacks %s", want)
		}
	}
	for _, want := range []string{"Bash(atl done *)", "Bash(atl note *)", "Bash(atl notes *)", "Bash(atl new *)", "Bash(atl open *)", "Bash(atl rename *)", "Bash(atl status *)"} {
		if !contains(strList(t, perms["ask"]), want) {
			t.Errorf("ask lacks %s", want)
		}
	}
	// state-changing commands are never auto-allowed
	for _, r := range strList(t, perms["allow"]) {
		for _, cmd := range []string{"rename", "note", "status"} {
			if strings.Contains(r, "atl "+cmd) {
				t.Errorf("allow has state-changing rule %s", r)
			}
		}
	}
	hooks := m["hooks"].(map[string]any)
	if len(hooks) != 1 {
		t.Errorf("hooks = %v (want only PreToolUse)", hooks)
	}
	pre := hooks["PreToolUse"].([]any)
	if len(pre) != 1 {
		t.Fatalf("PreToolUse = %v", pre)
	}
	g := pre[0].(map[string]any)
	if g["matcher"] != "Edit|Write|MultiEdit|NotebookEdit" {
		t.Errorf("matcher = %v", g["matcher"])
	}
	h := g["hooks"].([]any)[0].(map[string]any)
	if h["command"] != `'/opt/my atl/atl' hook AssistantGuard` || h["type"] != "command" {
		t.Errorf("hook = %v", h)
	}
}

// ruleMatches reports whether permission rule matches Bash command c the
// way Claude Code matches rules: "Bash(pattern)" with * matching any run of
// characters (spaces included), and the legacy "Bash(prefix:*)".
func ruleMatches(rule, c string) bool {
	if !strings.HasPrefix(rule, "Bash(") || !strings.HasSuffix(rule, ")") {
		return false
	}
	pat := strings.TrimSuffix(strings.TrimPrefix(rule, "Bash("), ")")
	if p, ok := strings.CutSuffix(pat, ":*"); ok {
		return c == p || strings.HasPrefix(c, p+" ")
	}
	var re strings.Builder
	re.WriteString("^")
	for i, part := range strings.Split(pat, "*") {
		if i > 0 {
			re.WriteString(".*")
		}
		re.WriteString(regexp.QuoteMeta(part))
	}
	re.WriteString("$")
	return regexp.MustCompile(re.String()).MatchString(c)
}

// TestAssistantNotesPermissions checks that no allow rule lets a notes
// write run without asking, however --set is spelled (an ask rule that
// matches wins over allow; a command no rule matches asks in the
// default mode), and that notes can still be read without asking.
func TestAssistantNotesPermissions(t *testing.T) {
	if !ruleMatches("Bash(atl show *)", "atl show x --json") || ruleMatches("Bash(atl note *)", "atl notes x") ||
		!ruleMatches("Bash(atl ls:*)", "atl ls") || ruleMatches("Bash(atl notes *)", "atl notes-x") {
		t.Fatal("ruleMatches is broken")
	}
	matchesAny := func(rules []string, c string) bool {
		for _, r := range rules {
			if ruleMatches(r, c) {
				return true
			}
		}
		return false
	}
	asks := []string{ // writes, and atl notes itself (its --set form writes)
		"atl notes fix --set", "atl notes --set fix", "atl notes fix --set=true", `atl notes fix "--set"`,
		"atl notes fix '--set'", `atl notes fix --s""et`, "atl notes fix --set < /tmp/x", "atl notes  fix --set",
		"atl notes\tfix --set", "atl note fix hello", "atl note fix --author assistant hello", "atl notes fix",
		"atl notes fix --clear", "atl notes --clear fix", "atl notes fix --clear=true", "atl notes fix --set --clear",
	}
	for _, c := range asks {
		if matchesAny(assistantAllow, c) {
			t.Errorf("allow rule lets %q run without asking", c)
		}
	}
	for _, c := range []string{"atl notes fix --set", "atl notes --set fix", "atl notes fix --set=true", `atl notes fix "--set"`, "atl note fix hello",
		"atl notes fix --clear", "atl notes --clear fix"} {
		if !matchesAny(assistantAsk, c) {
			t.Errorf("no ask rule for %q", c)
		}
	}
	for _, c := range []string{"atl show fix --notes", "atl show fix --json"} {
		if !matchesAny(assistantAllow, c) || matchesAny(assistantAsk, c) {
			t.Errorf("%q is not allowed without asking", c)
		}
	}
}

func TestAssistantSettingsMerge(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, ".claude", "settings.json")
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	user := `{
  "model": "opus",
  "permissions": {
    "defaultMode": "bypassPermissions",
    "allow": ["Bash(git log:*)", "Read", "Bash(atl note:*)", "Bash(atl ls:*)", "Bash(rm *)", "Bash(atl rename *)", "Bash(atl rename:*)", "Bash(atl notes *)", "Bash(atl notes:*)"],
    "ask": ["Bash(rm:*)", "Bash(atl pr:*)", "Bash(atl pr *)"],
    "deny": ["Bash(atl done:*)", "Bash(atl done *)", "Bash(git push *)", "Bash(curl *)"]
  },
  "hooks": {
    "PreToolUse": [{"matcher": "Bash", "hooks": [{"type": "command", "command": "my-hook"}]}],
    "Stop": [{"hooks": [{"type": "command", "command": "notify-send done"}]}]
  }
}`
	if err := os.WriteFile(path, []byte(user), 0o644); err != nil {
		t.Fatal(err)
	}
	for i := 0; i < 3; i++ {
		bin := "/usr/bin/atl"
		if i == 2 {
			bin = "/new/place/atl" // moved binary: old entry still replaced
		}
		if err := WriteAssistantFiles(dir, bin); err != nil {
			t.Fatal(err)
		}
	}
	m := readAssistantSettings(t, dir)
	if m["model"] != "opus" {
		t.Errorf("model lost: %v", m["model"])
	}
	perms := m["permissions"].(map[string]any)
	if perms["defaultMode"] != "default" {
		t.Errorf("defaultMode = %v", perms["defaultMode"])
	}
	wantAllow := append([]string{"Bash(git log:*)"}, assistantAllow...)
	if got := strList(t, perms["allow"]); !reflect.DeepEqual(got, wantAllow) {
		t.Errorf("allow = %v\nwant %v", got, wantAllow)
	}
	wantAsk := append([]string{"Bash(rm:*)"}, assistantAsk...)
	if got := strList(t, perms["ask"]); !reflect.DeepEqual(got, wantAsk) {
		t.Errorf("ask = %v\nwant %v", got, wantAsk)
	}
	// User deny entries are kept, even ones matching atelier allow/ask
	// rules; atelier's deny rules are not duplicated.
	wantDeny := append([]string{"Bash(atl done:*)", "Bash(atl done *)", "Bash(curl *)"}, assistantDeny...)
	if got := strList(t, perms["deny"]); !reflect.DeepEqual(got, wantDeny) {
		t.Errorf("deny = %v\nwant %v", got, wantDeny)
	}
	hooks := m["hooks"].(map[string]any)
	pre := hooks["PreToolUse"].([]any)
	if len(pre) != 2 {
		t.Fatalf("PreToolUse = %v", pre)
	}
	if c := pre[0].(map[string]any)["hooks"].([]any)[0].(map[string]any)["command"]; c != "my-hook" {
		t.Errorf("user hook = %v", c)
	}
	if c := pre[1].(map[string]any)["hooks"].([]any)[0].(map[string]any)["command"]; c != "'/new/place/atl' hook AssistantGuard" {
		t.Errorf("atelier hook = %v", c)
	}
	if _, ok := hooks["Stop"]; !ok {
		t.Error("user Stop hook lost")
	}

	// idempotent byte for byte
	before, _ := os.ReadFile(path)
	if err := WriteAssistantFiles(dir, "/new/place/atl"); err != nil {
		t.Fatal(err)
	}
	after, _ := os.ReadFile(path)
	if string(before) != string(after) {
		t.Errorf("not idempotent:\n%s\n---\n%s", before, after)
	}
}

func TestAssistantSettingsInvalidPermissions(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, ".claude", "settings.json")
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	orig := `{"permissions": {"allow": "Read"}, "x": 1}`
	if err := os.WriteFile(path, []byte(orig), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := WriteAssistantFiles(dir, "atl"); err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(path + ".bak"); string(b) != orig {
		t.Errorf("backup = %q", b)
	}
	m := readAssistantSettings(t, dir)
	if got := strList(t, m["permissions"].(map[string]any)["allow"]); !reflect.DeepEqual(got, assistantAllow) {
		t.Errorf("allow = %v", got)
	}
	if m["x"] == nil {
		t.Error("other key lost")
	}
}

func TestRetiredAssistantRules(t *testing.T) {
	for _, want := range []string{"Bash(atl ls:*)", "Bash(atl --help:*)", "Bash(atl open:*)", "Bash(atl note:*)"} {
		if !contains(retiredAssistantRules, want) {
			t.Errorf("retired lacks %s", want)
		}
	}
	if len(retiredAssistantRules) != len(assistantAllow)+len(assistantAsk)-3 { // Read, Grep, Glob
		t.Errorf("retired = %v", retiredAssistantRules)
	}
	for _, l := range [][]string{assistantAllow, assistantAsk, assistantDeny} {
		for _, r := range l {
			if strings.Contains(r, ":*") {
				t.Errorf("rule %s uses the legacy :* form", r)
			}
		}
	}
}

func contains(l []string, s string) bool {
	for _, x := range l {
		if x == s {
			return true
		}
	}
	return false
}
