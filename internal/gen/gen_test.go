type settingsFile struct {
	Hooks map[string][]struct {
		Matcher string `json:"matcher"`
		Hooks   []struct {
			Type    string `json:"type"`
			Command string `json:"command"`
		} `json:"hooks"`
	} `json:"hooks"`
}

func readSettings(t *testing.T, dir string) (settingsFile, map[string]any, string) {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(dir, ".claude", "settings.json"))
	if err != nil {
		t.Fatal(err)
	}
	var sf settingsFile
	if err := json.Unmarshal(b, &sf); err != nil {
		t.Fatalf("invalid json: %v\n%s", err, b)
	}
	var raw map[string]any
	if err := json.Unmarshal(b, &raw); err != nil {
		t.Fatal(err)
	}
	return sf, raw, string(b)
}

// atelierCount returns how many hook commands equal want under event.
func atelierCount(sf settingsFile, event, want string) int {
	n := 0
	for _, g := range sf.Hooks[event] {
		for _, h := range g.Hooks {
			if h.Command == want {
				n++
			}
		}
	}
	return n
}

func checkAtelierHooks(t *testing.T, sf settingsFile, atlBin string) {
	t.Helper()
	for _, ev := range hookEvents {
		want := HookCommand(atlBin, ev.Name)
		if n := atelierCount(sf, ev.Name, want); n != 1 {
			t.Errorf("%s: %d entries with command %q, want 1", ev.Name, n, want)
		}
		for _, g := range sf.Hooks[ev.Name] {
			for _, h := range g.Hooks {
				if h.Command == want {
					if h.Type != "command" || g.Matcher != ev.Matcher {
						t.Errorf("%s: entry %+v matcher %q", ev.Name, h, g.Matcher)
					}
				}
			}
		}
	}
}

func TestWriteSettingsFresh(t *testing.T) {
	dir := t.TempDir()
	if err := WriteSettings(dir, "/usr/local/bin/atl"); err != nil {
		t.Fatal(err)
	}
	sf, raw, text := readSettings(t, dir)
	checkAtelierHooks(t, sf, "/usr/local/bin/atl")
	if len(raw) != 1 || len(sf.Hooks) != len(hookEvents) {
		t.Errorf("unexpected keys: %s", text)
	}
	if !strings.Contains(text, `"command": "'/usr/local/bin/atl' hook PreToolUse"`) ||
		!strings.Contains(text, `"matcher": "Edit|Write|MultiEdit|NotebookEdit"`) {
		t.Errorf("unexpected content:\n%s", text)
	}
	if !strings.Contains(text, "\n  \"hooks\": {\n    \"") {
		t.Errorf("not 2-space indented:\n%s", text)
	}
	ents, _ := os.ReadDir(filepath.Join(dir, ".claude"))
	if len(ents) != 1 {
		t.Errorf("leftover files in .claude: %v", ents)
	}
}

func TestWriteSettingsMerge(t *testing.T) {
	dir := t.TempDir()
	if err := os.MkdirAll(filepath.Join(dir, ".claude"), 0o755); err != nil {
		t.Fatal(err)
	}
	existing := `{
  "permissions": {"allow": ["Bash(make test)"]},
  "model": "opus",
  "cleanupPeriodDays": 30,
  "hooks": {
    "Stop": [
      {"hooks": [{"type": "command", "command": "notify-send done"}]},
      {"hooks": [{"type": "command", "command": "'/old/path/atl' hook Stop"}]}
    ],
    "PreToolUse": [
      {"matcher": "Bash", "hooks": [{"type": "command", "command": "/home/u/bin/guard.sh", "timeout": 5}]},
      {"matcher": "Edit|Write|MultiEdit|NotebookEdit", "hooks": [{"type": "command", "command": "/old/atl hook PreToolUse"}]}
    ],
    "PostToolUse": [
      {"hooks": [{"type": "command", "command": "my-tool hook PostToolUse"}, {"type": "command", "command": "atl hook PostToolUse"}]}
    ]
  }
}`
	path := filepath.Join(dir, ".claude", "settings.json")
	if err := os.WriteFile(path, []byte(existing), 0o644); err != nil {
		t.Fatal(err)
	}
	const bin = "/opt/atl/bin/atl"
	for i := 0; i < 3; i++ { // idempotent
		if err := WriteSettings(dir, bin); err != nil {
			t.Fatal(err)
		}
	}
	sf, raw, text := readSettings(t, dir)
	checkAtelierHooks(t, sf, bin)
	if raw["model"] != "opus" || raw["cleanupPeriodDays"] != float64(30) {
		t.Errorf("top-level keys lost:\n%s", text)
	}
	if perms, _ := raw["permissions"].(map[string]any); perms == nil || len(perms["allow"].([]any)) != 1 {
		t.Errorf("permissions lost:\n%s", text)
	}
	for _, keep := range []string{`"notify-send done"`, `"/home/u/bin/guard.sh"`, `"timeout": 5`, `"matcher": "Bash"`, `"my-tool hook PostToolUse"`} {
		if strings.Count(text, keep) != 1 {
			t.Errorf("user entry %s not preserved exactly once:\n%s", keep, text)
		}
	}
	for _, gone := range []string{"/old/path/atl", "/old/atl", `"atl hook PostToolUse"`} {
		if strings.Contains(text, gone) {
			t.Errorf("stale atelier entry %s kept:\n%s", gone, text)
		}
	}
	if n := len(sf.Hooks["Stop"]); n != 2 {
		t.Errorf("Stop groups = %d, want 2 (user + atelier):\n%s", n, text)
	}
	if n := len(sf.Hooks["PostToolUse"]); n != 2 {
		t.Errorf("PostToolUse groups = %d, want 2:\n%s", n, text)
	}
	if _, err := os.Stat(path + ".bak"); err == nil {
		t.Error("valid settings should not be backed up")
	}
}

func TestWriteSettingsInvalidJSON(t *testing.T) {
	for _, bad := range []string{`{"permissions": `, `[1,2]`, `{"hooks": []}`, `{"hooks": {"Stop": {}}}`, `null`} {
		dir := t.TempDir()
		path := filepath.Join(dir, ".claude", "settings.json")
		os.MkdirAll(filepath.Dir(path), 0o755)
		if err := os.WriteFile(path, []byte(bad), 0o644); err != nil {
			t.Fatal(err)
		}
		if err := WriteSettings(dir, "/bin/atl"); err != nil {
			t.Fatalf("%s: %v", bad, err)
		}
		sf, _, _ := readSettings(t, dir)
		checkAtelierHooks(t, sf, "/bin/atl")
		if b, err := os.ReadFile(path + ".bak"); err != nil || string(b) != bad {
			t.Errorf("%s: backup = %q, %v", bad, b, err)
		}
	}
}

func TestWriteSettingsQuotedBin(t *testing.T) {
	dir := t.TempDir()
	bin := "/home/my user/it's bin/atl"
	for i := 0; i < 2; i++ {
		if err := WriteSettings(dir, bin); err != nil {
			t.Fatal(err)
		}
	}
	sf, _, text := readSettings(t, dir)
	want := `'/home/my user/it'\''s bin/atl' hook Stop`
	if HookCommand(bin, "Stop") != want {
		t.Fatalf("HookCommand = %q, want %q", HookCommand(bin, "Stop"), want)
	}
	checkAtelierHooks(t, sf, bin)
	// Switching binaries replaces the entries rather than adding new ones.
	if err := WriteSettings(dir, "/usr/bin/atl"); err != nil {
		t.Fatal(err)
	}
	sf, _, text = readSettings(t, dir)
	checkAtelierHooks(t, sf, "/usr/bin/atl")
	if strings.Contains(text, "my user") {
		t.Errorf("old quoted entry kept:\n%s", text)
	}
}

func TestIsAtelierCommand(t *testing.T) {
	bin := "/x y/atelier-dev"
	for _, c := range []struct {
		cmd  string
		want bool
	}{
		{"'/usr/bin/atl' hook Stop", true},
		{"/usr/bin/atl hook Stop", true},
		{"atl hook Stop", true},
		{`"/a b/atl" hook Stop`, true},
		{`/a\ b/atl hook Stop`, true},
		{"'/x y/atelier-dev' hook Stop", true},
		{"'/usr/bin/atl' hook Start", false},
		{"/usr/bin/atl hook Stop --x", false},
		{"my-atl hook Stop", false},
		{"notify-send hook Stop", false},
		{"/usr/bin/atlas hook Stop", false},
		{"/home/u/bin/atl-dev hook Stop", true},
		{"'/home/u/go/bin/atl_old' hook Stop", true},
		{"atl2 hook Stop", true},
		{"/usr/bin/atl-dev hook Start", false},
		{"/usr/bin/atl x hook Stop", false},
		{"/usr/bin/atl  hook Stop", true},
		{"/usr/bin/xatl hook Stop", false},
		{" hook Stop", false},
	} {
		if got := isAtelierCommand(c.cmd, "Stop", bin); got != c.want {
			t.Errorf("isAtelierCommand(%q) = %v, want %v", c.cmd, got, c.want)
		}
	}
}

func TestWriteSettingsRenamedBinary(t *testing.T) {
	dir := t.TempDir()
	if err := WriteSettings(dir, "/home/u/go/bin/atl-dev"); err != nil {
		t.Fatal(err)
	}
	if err := WriteSettings(dir, "/usr/local/bin/atl"); err != nil {
		t.Fatal(err)
	}
	sf, _, text := readSettings(t, dir)
	checkAtelierHooks(t, sf, "/usr/local/bin/atl")
	if strings.Contains(text, "atl-dev") {
		t.Errorf("entries of the renamed binary kept:\n%s", text)
	}
	for _, ev := range hookEvents {
		if n := len(sf.Hooks[ev.Name]); n != 1 {
			t.Errorf("%s: %d groups, want 1:\n%s", ev.Name, n, text)
		}
	}
}

