func TestWriteClaudeMD(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "tasks", "fix-login")
	task := model.Task{Slug: "fix-login", Title: "Fix login", Description: "Users cannot log in with SSO.",
		Branch: "atl/fix-login", PortOffset: 200}
	repos := []RepoInfo{
		{Name: "api", Mode: model.ModeRW, Path: "/home/u/tasks/fix-login/api"},
		{Name: "design-system", Mode: model.ModeRO, Path: "/home/u/repos/design-system"},
	}
	if err := WriteClaudeMD(dir, task, repos); err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(filepath.Join(dir, "CLAUDE.md"))
	if err != nil {
		t.Fatal(err)
	}
	got := string(b)
	for _, want := range []string{
		"<!-- generated by atelier",
		"# Fix login\n",
		"Users cannot log in with SSO.",
		"`atl/fix-login`",
		"**api** — `/home/u/tasks/fix-login/api` — **rw**",
		"git worktree on branch `atl/fix-login`",
		"**design-system** — `/home/u/repos/design-system` — **ro**",
		"must NOT be modified by any means",
		"blocked by an atelier hook",
		"Edit, Write",
		"Bash",
		"`sed -i`",
		"`tee`",
		"`git commit`",
		"`checkout`",
		"`stash`",
		"`reset`",
		"formatters",
		"package installs",
		"build artifacts",
		"`git log`",
		"`ATL_PORT_OFFSET=200`",
		"${ATL_PORT_OFFSET}",
		"$((3000 + ATL_PORT_OFFSET))",
		"exported in the environment",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("CLAUDE.md missing %q\n---\n%s", want, got)
		}
	}
	if !strings.HasPrefix(got, "<!-- generated by atelier") {
		t.Errorf("CLAUDE.md should start with the generated comment")
	}
}

